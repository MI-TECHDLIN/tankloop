import 'dart:convert';
import 'dart:io';
import 'package:tankloop_domain/domain.dart';

/// Usage: dart run packages/domain/bin/simulate.dart --seed=20261101 --days=10
///        --format=sql|json|summary
void main(List<String> args) {
  final options = <String, String>{};
  for (final argument in args) {
    final split = argument.indexOf('=');
    if (!argument.startsWith('--') || split < 0) {
      throw const FormatException(
        'Use --seed=N --days=N --format=sql|json|summary',
      );
    }
    final key = argument.substring(2, split);
    if (!{'seed', 'days', 'format'}.contains(key)) {
      throw FormatException('Unknown option: $key');
    }
    options[key] = argument.substring(split + 1);
  }
  final seed = int.parse(options['seed'] ?? '20261101');
  final days = int.parse(options['days'] ?? '10');
  if (days < 0 || days > 365) {
    throw const FormatException('Days must be between 0 and 365.');
  }
  final engine = SimulationEngine(seed: seed)..advance(Duration(days: days));
  switch (options['format'] ?? 'summary') {
    case 'json':
      stdout.writeln(
        const JsonEncoder.withIndent('  ').convert(engine.toJson()),
      );
    case 'sql':
      _writeSql(engine);
    case 'summary':
      stdout.writeln(
        const JsonEncoder.withIndent('  ').convert({
          'is_simulated': true,
          'seed': seed,
          'simulated_at': engine.now.toIso8601String(),
          'organizations': engine.organizations.length,
          'facilities': engine.facilities.length,
          'assets': engine.assets.length,
          'sampling_points': engine.points.length,
          'inspections': engine.inspections.length,
          'samples': engine.samples.length,
          'results_by_state': {
            for (final state in ResultState.values)
              state.name: engine.results.values
                  .where((r) => r.state == state)
                  .length,
          },
          'incidents_by_state': {
            for (final state in IncidentState.values)
              state.name: engine.incidents.values
                  .where((i) => i.state == state)
                  .length,
          },
          'audit_events': engine.auditEvents.length,
          'public_token': engine.featuredToken,
        }),
      );
    default:
      throw const FormatException('Format must be sql, json or summary.');
  }
}

String _sql(Object? value, String key) {
  if (value == null) return 'null';
  if (value is num || value is bool) return '$value';
  if (key == 'point_ids') {
    return 'array[${(value as List).map((id) => _sql(id, 'id')).join(',')}]::uuid[]';
  }
  if (value is Map || value is List) {
    return "'${jsonEncode(value).replaceAll("'", "''")}'::jsonb";
  }
  return "'${value.toString().replaceAll("'", "''")}'";
}

void _insert(String table, Map<String, Object?> row) => stdout.writeln(
  'insert into $table (${row.keys.join(',')}) values (${row.entries.map((e) => _sql(e.value, e.key)).join(',')});',
);

void _writeSql(SimulationEngine engine) {
  final ids = SeededRandom(engine.seed + 101);
  stdout.writeln(
    '-- GENERATED by packages/domain/bin/simulate.dart. Do not edit by hand.',
  );
  stdout.writeln(
    '-- Fully simulated workload. No measured water-quality or pilot evidence.',
  );
  stdout.writeln(
    '-- Seed ${engine.seed}; simulated clock ${engine.now.toIso8601String()}. Apply to a fresh local database.',
  );
  stdout.writeln('begin;');
  for (final organization in engine.organizations) {
    _insert('public.organizations', {
      ...organization.toJson(),
      'settings': {
        'simulation_seed': engine.seed,
        'simulation_clock': engine.now.toIso8601String(),
        'model_version': 1,
      },
    });
  }
  for (final facility in engine.facilities) {
    _insert('public.facilities', facility.toJson());
  }
  for (final actor in engine.actors) {
    // Synthetic identities have no password or session. Create your own local
    // Auth user and grant it membership to exercise the authenticated app.
    _insert('auth.users', {
      'id': actor.id,
      'instance_id': '00000000-0000-0000-0000-000000000000',
      'aud': 'authenticated',
      'role': 'authenticated',
      'email': 'sim.${actor.role.name}.${actor.id}@tankloop.invalid',
      'email_confirmed_at': engine.startsAt.toIso8601String(),
      'raw_app_meta_data': {
        'provider': 'email',
        'providers': ['email'],
      },
      'raw_user_meta_data': {'is_simulated': true},
      'created_at': engine.startsAt.toIso8601String(),
      'updated_at': engine.startsAt.toIso8601String(),
    });
    _insert('public.memberships', {
      'id': ids.uuid(),
      'user_id': actor.id,
      ...actor.scope.toJson(),
      'role': actor.role.name,
      'is_simulated': true,
    });
  }
  for (final system in engine.systems) {
    _insert('public.water_systems', system.toJson());
  }
  for (final asset in engine.assets) {
    _insert('public.assets', asset.toJson());
  }
  for (final point in engine.points) {
    _insert('public.sampling_points', point.toJson());
  }
  for (final template in engine.templates) {
    _insert('public.checklist_templates', template.toJson());
  }
  for (final task in engine.inspections.values) {
    final submission = engine.submissions[task.id];
    _insert('public.inspections', {
      ...task.toJson(),
      'state': task.isSubmitted ? 'submitted' : 'scheduled',
      'observed_at': submission?.observedAt.toUtc().toIso8601String(),
      'submitted_by': task.isSubmitted
          ? engine.actorFor(task.scope, Role.field).id
          : null,
      'answers':
          submission?.answers.map(
            (key, value) => MapEntry(key, value.toJson()),
          ) ??
          <String, Object?>{},
      'notes': submission?.notes ?? '',
    });
  }
  for (final sample in engine.samples.values) {
    _insert('public.samples', {
      ...sample.toJson(),
      'preservation_note':
          'Simulated sealed container and transport record; not a real sample.',
    });
  }
  for (final event in engine.custody) {
    _insert('public.custody_events', event.toJson());
  }
  for (final result in engine.results.values) {
    _insert('public.test_results', result.toJson());
  }
  for (final incident in engine.incidents.values) {
    _insert('public.incidents', incident.toJson());
    final plan = incident.plan;
    if (plan == null) continue;
    for (final point in plan.pointIds) {
      _insert('public.verification_requirements', {
        'id': ids.uuid(),
        ...incident.scope.toJson(),
        'incident_id': incident.id,
        'kind': 'sample',
        'point_id': point,
        'indicator': wireName(plan.indicator),
        'method': plan.method,
        'not_before': plan.notBefore.toUtc().toIso8601String(),
        'is_simulated': true,
      });
    }
    for (final template in plan.checklistIds) {
      _insert('public.verification_requirements', {
        'id': ids.uuid(),
        ...incident.scope.toJson(),
        'incident_id': incident.id,
        'kind': 'checklist',
        'template_id': template,
        'not_before': plan.notBefore.toUtc().toIso8601String(),
        'is_simulated': true,
      });
    }
  }
  for (final work in engine.workOrders.values) {
    // Photo links are command-scoped rows in field_evidence, not columns on work_orders.
    _insert('public.work_orders', work.toJson()..remove('evidence'));
  }
  for (final qr in engine.qrs) {
    _insert('public.public_records', {'id': ids.uuid(), ...qr.toJson()});
  }
  for (final event in engine.auditEvents) {
    _insert('public.audit_events', event.toJson());
  }
  stdout.writeln('commit;');
}
